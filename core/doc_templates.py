"""
Word (.docx) export templates.

A template is a Word document whose styles, page setup, header and footer shape
every export; its body text is ignored. Built-in templates ship in
core/docx_templates/ (generated by tools/build_docx_templates.py, except
classic.docx). User templates live in <app data>/docx_templates/ with an
index.json, shared by every profile.

IDs: "builtin:<id>" and "user:<id>". Each series stores its choice in
`docTemplate` ("" follows the app default, config `docTemplateDefault`, which in
turn falls back to builtin:classic).
"""

import json
import re
import shutil
import sys
import uuid
import zipfile
from datetime import datetime
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from .storage.config import get_app_data_dir, get_config, update_config

BUILTIN = "builtin:"
USER = "user:"
FALLBACK_ID = "builtin:classic"
LEGACY_FILENAME = "TemplateNew.docx"
MAX_TEMPLATE_BYTES = 25 * 1024 * 1024

# Styles the exporter writes with. Missing ones are created on the fly at export.
USED_STYLES = ("Normal", "Heading 1", "Heading 2", "Heading 3", "Heading 4")

_DOCX_MAIN = "application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"
_DOTX_MAIN = "application/vnd.openxmlformats-officedocument.wordprocessingml.template.main+xml"
_DOTM_MAIN = "application/vnd.ms-word.template.macroEnabledTemplate.main+xml"


# ── Locations ────────────────────────────────────────────────────────────────

def _builtin_dir() -> Path:
    if getattr(sys, "frozen", False):
        return Path(sys._MEIPASS) / "core" / "docx_templates"
    return Path(__file__).resolve().parent / "docx_templates"


def _user_dir() -> Path:
    return get_app_data_dir() / "docx_templates"


def _user_index_path() -> Path:
    return _user_dir() / "index.json"


@lru_cache(maxsize=1)
def _builtin_index() -> List[Dict[str, Any]]:
    try:
        return json.loads((_builtin_dir() / "index.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return []


def _load_user_index() -> Dict[str, Any]:
    try:
        data = json.loads(_user_index_path().read_text(encoding="utf-8"))
        if isinstance(data, dict):
            data.setdefault("templates", [])
            return data
    except (OSError, json.JSONDecodeError):
        pass
    return {"templates": [], "legacyImported": False}


def _save_user_index(data: Dict[str, Any]):
    _user_dir().mkdir(parents=True, exist_ok=True)
    _user_index_path().write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")


# ── Legacy TemplateNew.docx ──────────────────────────────────────────────────

def _legacy_candidates() -> List[Path]:
    paths = [get_app_data_dir() / LEGACY_FILENAME]
    if getattr(sys, "frozen", False):
        paths.append(Path(sys.executable).parent / LEGACY_FILENAME)
    return paths


def _migrate_legacy():
    """Import a hand-placed TemplateNew.docx once, and keep it as the default.

    Older versions preferred %APPDATA%/lwntl/TemplateNew.docx (or one next to
    the .exe) over the bundled file; importing it keeps those exports unchanged.
    """
    data = _load_user_index()
    if data.get("legacyImported"):
        return
    data["legacyImported"] = True
    legacy = next((p for p in _legacy_candidates() if p.exists()), None)
    if legacy is None:
        _save_user_index(data)
        return
    try:
        entry = _store_file(legacy, "TemplateNew (lama)", data)
        if not get_config().get("docTemplateDefault"):
            update_config({"docTemplateDefault": entry["id"]})
        print(f"[DocTemplates] Imported legacy {legacy} as {entry['id']}")
    except Exception as e:
        print(f"[DocTemplates] Legacy import skipped: {e}")
        _save_user_index(data)


# ── Inspection ───────────────────────────────────────────────────────────────

_PAGE_SIZES = (
    ("A4", 21.0, 29.7), ("A5", 14.8, 21.0), ("A6", 10.5, 14.8), ("B5", 17.6, 25.0),
    ("B5 (JIS)", 18.2, 25.7), ("B6 (JIS)", 12.8, 18.2), ("Letter", 21.59, 27.94),
    ("Legal", 21.59, 35.56), ("6 × 9 in", 15.24, 22.86), ("5 × 8 in", 12.7, 20.32),
    ("5.5 × 8.5 in", 13.97, 21.59),
)
_ALIGN = {0: "left", 1: "center", 2: "right", 3: "justify"}


def _cm(length) -> Optional[float]:
    return round(length.cm, 2) if length is not None else None


def _pt(length) -> Optional[float]:
    return round(length.pt, 1) if length is not None else None


def _page_name(w: float, h: float) -> str:
    short, long_ = sorted((w, h))
    for name, a, b in _PAGE_SIZES:
        if abs(short - a) < 0.15 and abs(long_ - b) < 0.15:
            return name
    return f"{w:.1f} × {h:.1f} cm"


def _theme_fonts(doc) -> Dict[str, str]:
    try:
        from docx.opc.constants import RELATIONSHIP_TYPE as RT
        blob = doc.part.part_related_by(RT.THEME).blob.decode("utf-8", "ignore")
        major = re.search(r"<a:majorFont>\s*<a:latin typeface=\"([^\"]*)\"", blob)
        minor = re.search(r"<a:minorFont>\s*<a:latin typeface=\"([^\"]*)\"", blob)
        return {"major": major.group(1) if major else "", "minor": minor.group(1) if minor else ""}
    except Exception:
        return {"major": "", "minor": ""}


def _defaults(doc) -> Dict[str, Any]:
    """Document-wide run/paragraph defaults (w:docDefaults)."""
    from docx.oxml.ns import qn
    out: Dict[str, Any] = {}
    dd = doc.styles.element.find(qn("w:docDefaults"))
    if dd is None:
        return out
    fonts = dd.find(f"{qn('w:rPrDefault')}/{qn('w:rPr')}/{qn('w:rFonts')}")
    if fonts is not None:
        out["font"] = fonts.get(qn("w:ascii")) or ""
        out["fontTheme"] = fonts.get(qn("w:asciiTheme")) or ""
    sz = dd.find(f"{qn('w:rPrDefault')}/{qn('w:rPr')}/{qn('w:sz')}")
    if sz is not None and sz.get(qn("w:val")):
        out["sizePt"] = int(sz.get(qn("w:val"))) / 2
    sp = dd.find(f"{qn('w:pPrDefault')}/{qn('w:pPr')}/{qn('w:spacing')}")
    if sp is not None:
        out["spacing"] = {k: sp.get(qn(f"w:{k}")) for k in ("before", "after", "line", "lineRule")}
    return out


def _style_chain(style):
    while style is not None:
        yield style
        style = style.base_style


def _style_font(style, defaults, theme) -> str:
    from docx.oxml.ns import qn
    for st in _style_chain(style):
        rpr = st.element.rPr
        fonts = rpr.find(qn("w:rFonts")) if rpr is not None else None
        if fonts is not None:
            t = fonts.get(qn("w:asciiTheme"))
            if t:
                return theme["major" if t.startswith("major") else "minor"] or ""
            if fonts.get(qn("w:ascii")):
                return fonts.get(qn("w:ascii"))
    if defaults.get("font"):
        return defaults["font"]
    t = defaults.get("fontTheme", "")
    return theme["major" if t.startswith("major") else "minor"] if t else ""


def _first(style, getter):
    for st in _style_chain(style):
        v = getter(st)
        if v is not None:
            return v
    return None


def _line_spacing(style, defaults) -> Dict[str, Any]:
    from docx.enum.text import WD_LINE_SPACING
    for st in _style_chain(style):
        pf = st.paragraph_format
        if pf.line_spacing is None:
            continue
        rule = pf.line_spacing_rule
        if isinstance(pf.line_spacing, float):
            return {"kind": "multiple", "value": round(pf.line_spacing, 2)}
        kind = "atLeast" if rule == WD_LINE_SPACING.AT_LEAST else "exact"
        return {"kind": kind, "value": _pt(pf.line_spacing)}
    sp = defaults.get("spacing") or {}
    if sp.get("line"):
        line = int(sp["line"])
        if (sp.get("lineRule") or "auto") == "auto":
            return {"kind": "multiple", "value": round(line / 240, 2)}
        return {"kind": "atLeast" if sp["lineRule"] == "atLeast" else "exact", "value": round(line / 20, 1)}
    return {"kind": "multiple", "value": 1.0}


def _spacing(style, defaults, which: str) -> float:
    v = _first(style, lambda st: getattr(st.paragraph_format, f"space_{which}"))
    if v is not None:
        return _pt(v)
    raw = (defaults.get("spacing") or {}).get(which)
    return round(int(raw) / 20, 1) if raw else 0.0


def _style_summary(doc, name: str, defaults, theme) -> Optional[Dict[str, Any]]:
    try:
        style = doc.styles[name]
    except KeyError:
        return None
    size = _first(style, lambda st: st.font.size)
    align = _first(style, lambda st: st.paragraph_format.alignment)
    indent = _first(style, lambda st: st.paragraph_format.first_line_indent)
    color = _first(style, lambda st: st.font.color.rgb if st.font.color and st.font.color.type is not None else None)
    return {
        "font": _style_font(style, defaults, theme),
        "sizePt": _pt(size) if size is not None else defaults.get("sizePt", 10.0),
        "bold": bool(_first(style, lambda st: st.font.bold)),
        "italic": bool(_first(style, lambda st: st.font.italic)),
        "color": f"#{color}" if color is not None else "",
        "align": _ALIGN.get(int(align), "left") if align is not None else "left",
        "lineSpacing": _line_spacing(style, defaults),
        "spaceBeforePt": _spacing(style, defaults, "before"),
        "spaceAfterPt": _spacing(style, defaults, "after"),
        "firstLineIndentCm": _cm(indent) or 0.0,
    }


def _has_content(part) -> bool:
    xml = part._element.xml
    return bool(re.search(r"<w:t[ >][^<]*\S", xml) or "w:fldChar" in xml or "w:fldSimple" in xml
                or "<w:drawing" in xml or "<w:pict" in xml)


def inspect_template(path: Path) -> Dict[str, Any]:
    """Describe what an export with this template will look like."""
    from docx import Document
    doc = Document(str(path))
    defaults, theme = _defaults(doc), _theme_fonts(doc)
    s = doc.sections[0]
    w, h = s.page_width.cm, s.page_height.cm
    body_text = sum(1 for p in doc.paragraphs if p.text.strip()) + len(doc.tables)
    return {
        "page": {"name": _page_name(w, h), "widthCm": round(w, 2), "heightCm": round(h, 2),
                 "landscape": w > h},
        "margins": {"top": _cm(s.top_margin), "bottom": _cm(s.bottom_margin),
                    "left": _cm(s.left_margin), "right": _cm(s.right_margin)},
        "body": _style_summary(doc, "Normal", defaults, theme),
        "heading": _style_summary(doc, "Heading 1", defaults, theme),
        "subheading": _style_summary(doc, "Heading 2", defaults, theme),
        "missingStyles": [n for n in USED_STYLES if _style_exists(doc, n) is False],
        "hasHeader": any(_has_content(sec.header) for sec in doc.sections if not sec.header.is_linked_to_previous)
                     or _has_content(s.header),
        "hasFooter": any(_has_content(sec.footer) for sec in doc.sections if not sec.footer.is_linked_to_previous)
                     or _has_content(s.footer),
        "sections": len(doc.sections),
        "bodyBlocks": body_text,
    }


def _style_exists(doc, name: str) -> bool:
    try:
        doc.styles[name]
        return True
    except KeyError:
        return False


def _safe_inspect(path: Optional[Path]) -> Tuple[Optional[Dict[str, Any]], str]:
    if path is None or not path.exists():
        return None, "File template tidak ditemukan."
    try:
        return inspect_template(path), ""
    except Exception as e:
        return None, f"Tidak bisa dibaca: {e}"


# ── Listing / lookup ─────────────────────────────────────────────────────────

def _builtin_entry(meta: Dict[str, Any], with_info: bool) -> Dict[str, Any]:
    entry = {"id": BUILTIN + meta["id"], "name": meta["name"], "description": meta.get("description", ""),
             "builtin": True, "fileName": meta["file"]}
    if with_info:
        entry["info"], entry["error"] = _safe_inspect(_builtin_dir() / meta["file"])
    return entry


def _user_entry(meta: Dict[str, Any], with_info: bool) -> Dict[str, Any]:
    entry = {"id": USER + meta["id"], "name": meta["name"], "description": meta.get("description", ""),
             "builtin": False, "fileName": meta.get("originalName") or meta["file"],
             "createdAt": meta.get("createdAt", "")}
    if with_info:
        entry["info"], entry["error"] = _safe_inspect(_user_dir() / meta["file"])
    return entry


def list_templates(with_info: bool = True) -> List[Dict[str, Any]]:
    _migrate_legacy()
    out = [_builtin_entry(m, with_info) for m in _builtin_index()]
    out += [_user_entry(m, with_info) for m in _load_user_index()["templates"]]
    return out


def _find_meta(template_id: str) -> Tuple[Optional[Dict[str, Any]], Optional[Path]]:
    if template_id.startswith(BUILTIN):
        key = template_id[len(BUILTIN):]
        meta = next((m for m in _builtin_index() if m["id"] == key), None)
        return (meta, _builtin_dir() / meta["file"]) if meta else (None, None)
    if template_id.startswith(USER):
        key = template_id[len(USER):]
        meta = next((m for m in _load_user_index()["templates"] if m["id"] == key), None)
        return (meta, _user_dir() / meta["file"]) if meta else (None, None)
    return None, None


def template_name(template_id: str) -> str:
    meta, _ = _find_meta(template_id)
    return meta["name"] if meta else ""


def template_path(template_id: str) -> Optional[Path]:
    _, path = _find_meta(template_id or "")
    return path if path is not None and path.exists() else None


def default_template_id() -> str:
    _migrate_legacy()
    try:
        chosen = get_config().get("docTemplateDefault") or ""
    except Exception:
        chosen = ""
    return chosen if template_path(chosen) else FALLBACK_ID


def resolve_for_series(series: Optional[Dict[str, Any]]) -> Tuple[str, Optional[Path]]:
    """(template id, path) used to export this series; path is None if nothing is usable."""
    chosen = (series or {}).get("docTemplate") or ""
    if chosen and template_path(chosen):
        return chosen, template_path(chosen)
    fallback = default_template_id()
    return fallback, template_path(fallback)


# ── User templates ───────────────────────────────────────────────────────────

def _as_docx_bytes(src: Path) -> bytes:
    """Read a .docx/.dotx/.dotm and return .docx bytes (templates get their content type rewritten)."""
    raw = src.read_bytes()
    if len(raw) > MAX_TEMPLATE_BYTES:
        raise ValueError("File terlalu besar (maksimal 25 MB).")
    try:
        zin = zipfile.ZipFile(src)
    except zipfile.BadZipFile:
        raise ValueError("Bukan file Word (.docx/.dotx). File .doc lama perlu disimpan ulang sebagai .docx di Word.")
    with zin:
        types = zin.read("[Content_Types].xml").decode("utf-8")
        if _DOCX_MAIN in types:
            return raw
        if _DOTX_MAIN not in types and _DOTM_MAIN not in types:
            raise ValueError("File ini bukan dokumen Word.")
        types = types.replace(_DOTX_MAIN, _DOCX_MAIN).replace(_DOTM_MAIN, _DOCX_MAIN)
        import io
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                data = types.encode("utf-8") if item.filename == "[Content_Types].xml" else zin.read(item.filename)
                if item.filename.lower().endswith("vbaproject.bin"):
                    continue  # never keep macros
                zout.writestr(item, data)
        return buf.getvalue()


def _store_file(src: Path, name: str, data: Dict[str, Any]) -> Dict[str, Any]:
    content = _as_docx_bytes(src)
    key = uuid.uuid4().hex[:10]
    _user_dir().mkdir(parents=True, exist_ok=True)
    dest = _user_dir() / f"{key}.docx"
    dest.write_bytes(content)
    try:
        inspect_template(dest)
    except Exception as e:
        dest.unlink(missing_ok=True)
        raise ValueError(f"Word tidak bisa membaca file ini: {e}")
    meta = {"id": key, "file": dest.name, "name": (name or src.stem).strip()[:80] or src.stem,
            "originalName": src.name, "createdAt": datetime.utcnow().isoformat() + "Z"}
    data["templates"].append(meta)
    _save_user_index(data)
    return _user_entry(meta, with_info=True)


def import_template(src: str, name: str = "") -> Dict[str, Any]:
    path = Path(src)
    if not path.exists():
        raise FileNotFoundError(f"File tidak ditemukan: {src}")
    data = _load_user_index()
    return _store_file(path, name or path.stem, data)


def rename_template(template_id: str, name: str) -> Dict[str, Any]:
    if not template_id.startswith(USER):
        raise ValueError("Template bawaan tidak bisa diganti namanya.")
    name = (name or "").strip()[:80]
    if not name:
        raise ValueError("Nama tidak boleh kosong.")
    data = _load_user_index()
    for meta in data["templates"]:
        if USER + meta["id"] == template_id:
            meta["name"] = name
            _save_user_index(data)
            return _user_entry(meta, with_info=False)
    raise KeyError("Template tidak ditemukan.")


def delete_template(template_id: str) -> bool:
    if not template_id.startswith(USER):
        raise ValueError("Template bawaan tidak bisa dihapus.")
    data = _load_user_index()
    keep, removed = [], None
    for meta in data["templates"]:
        if USER + meta["id"] == template_id:
            removed = meta
        else:
            keep.append(meta)
    if removed is None:
        return False
    data["templates"] = keep
    _save_user_index(data)
    (_user_dir() / removed["file"]).unlink(missing_ok=True)
    if get_config().get("docTemplateDefault") == template_id:
        update_config({"docTemplateDefault": ""})
    return True


def copy_template_to(template_id: str, dest: str) -> str:
    path = template_path(template_id)
    if path is None:
        raise FileNotFoundError("Template tidak ditemukan.")
    shutil.copyfile(path, dest)
    return dest


def set_default(template_id: str) -> str:
    if template_id and template_path(template_id) is None:
        raise KeyError("Template tidak ditemukan.")
    update_config({"docTemplateDefault": template_id or ""})
    return default_template_id()
